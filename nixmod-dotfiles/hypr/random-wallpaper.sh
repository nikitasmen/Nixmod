#!/usr/bin/env bash
# Pick a random wallpaper and write hyprpaper config (v0.8+ block syntax), restart hyprpaper.

WALLDIR="$HOME/Pictures/wallpapers"
CONF="$HOME/.config/hypr/hyprpaper.conf"
LAST_WALL="$HOME/.config/hypr/last_wallpaper.txt"

mkdir -p "$(dirname "$CONF")"

WALL=$(find -L "$WALLDIR" -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' \) 2>/dev/null | shuf -n 1)

if [[ -z "$WALL" ]]; then
  echo "❌ No wallpapers found in $WALLDIR" >&2
  exit 1
fi

# Avoid repeating the same wallpaper twice in a row (when more than one is available)
if [[ -f "$LAST_WALL" ]]; then
  COUNT=$(find -L "$WALLDIR" -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' \) 2>/dev/null | wc -l)
  if [[ "$COUNT" -gt 1 ]]; then
    while [[ "$WALL" == "$(cat "$LAST_WALL" 2>/dev/null)" ]]; do
      WALL=$(find -L "$WALLDIR" -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' \) 2>/dev/null | shuf -n 1)
    done
  fi
fi

[[ "$WALL" != /* ]] && WALL="$(cd "$(dirname "$WALL")" 2>/dev/null && pwd)/$(basename "$WALL")"
echo "$WALL" > "$LAST_WALL"

# Get active monitors using hyprctl
get_monitors() {
  if command -v jq &>/dev/null; then
    hyprctl -j monitors 2>/dev/null | jq -r '.[].name'
  else
    hyprctl monitors 2>/dev/null | awk '/Monitor/ {gsub(/:$/, "", $2); print $2}'
  fi
}

# hyprctl may not be ready yet at startup; retry briefly
for _ in 1 2 3 4 5; do
  MONS=($(get_monitors))
  [[ ${#MONS[@]} -gt 0 ]] && break
  sleep 0.5
done

# Generate the block-syntax config file (hyprpaper >= 0.8; "preload"/"wallpaper = MON,PATH" are gone)
{
  echo "# Autogenerated hyprpaper config"
  if [[ ${#MONS[@]} -gt 0 ]]; then
    for MON in "${MONS[@]}"; do
      echo "wallpaper {"
      echo "    monitor = $MON"
      echo "    path = $WALL"
      echo "    fit_mode = cover"
      echo "}"
    done
  else
    # Fallback: empty monitor = apply to any/all outputs
    echo "wallpaper {"
    echo "    monitor ="
    echo "    path = $WALL"
    echo "    fit_mode = cover"
    echo "}"
  fi
} > "$CONF"

echo "✅ Random wallpaper set to: $WALL"
